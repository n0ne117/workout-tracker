// Alias similar sports to their closest icon
const ALIAS = {
  other: 'other',
}

export default function SportIcon({ sport, size = 24, className = '' }) {
  const key = sport in PIXELS ? sport : 'other'
  const rows = PIXELS[key]
  const gridSize = 12
  const px = size / gridSize

  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${size} ${size}`}
      className={className}
      shapeRendering="crispEdges"
      aria-label={sport}
    >
      {rows.map((row, r) =>
        row.split('').map((cell, c) =>
          cell === '1' ? (
            <rect
              key={`${r}-${c}`}
              x={c * px}
              y={r * px}
              width={px}
              height={px}
              fill="currentColor"
            />
          ) : null
        )
      )}
    </svg>
  )
}
